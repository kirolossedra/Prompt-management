import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const milestonesPath = path.join(root, "docs", "roadmap", "milestones.yaml");
const outputPath = path.join(root, "docs", "roadmap", "generated-gantt.md");
const readmePath = path.join(root, "README.md");
const startMarker = "<!-- ROADMAP-GANTT:START -->";
const endMarker = "<!-- ROADMAP-GANTT:END -->";

function unquote(value) {
  const trimmed = value.trim();
  if ((trimmed.startsWith("'") && trimmed.endsWith("'")) || (trimmed.startsWith('"') && trimmed.endsWith('"'))) {
    return trimmed.slice(1, -1).replace(/''/g, "'");
  }
  return trimmed;
}

function parseMilestonesYaml(source) {
  const milestones = [];
  let current = null;
  let nested = null;

  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, "");
    const idMatch = line.match(/^  - id:\s*(.+)$/);
    if (idMatch) {
      current = { id: unquote(idMatch[1]) };
      milestones.push(current);
      nested = null;
      continue;
    }
    if (!current) continue;

    const topMatch = line.match(/^    ([a-zA-Z0-9_]+):\s*(.*)$/);
    if (topMatch) {
      const [, key, value] = topMatch;
      if (value === "") {
        nested = key;
        current[key] ??= {};
      } else {
        current[key] = unquote(value);
        nested = null;
      }
      continue;
    }

    const nestedMatch = line.match(/^      ([a-zA-Z0-9_]+):\s*(.+)$/);
    if (nestedMatch && nested) {
      const [, key, value] = nestedMatch;
      current[nested][key] = unquote(value);
    }
  }

  return milestones;
}

function taskId(value) {
  return value.replace(/[^a-zA-Z0-9]/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "").slice(0, 42) || "delivery";
}

function requireDate(milestone, field) {
  const value = milestone[field]?.value;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value || "")) {
    throw new Error(`${milestone.id}: ${field}.value must be YYYY-MM-DD.`);
  }
  return value;
}

function mermaidTask(milestone) {
  const start = requireDate(milestone, "start_date");
  const end = requireDate(milestone, "target_date");
  const timing = start === end ? `${start}, 1d` : `${start}, ${end}`;
  return `    ${milestone.name.padEnd(43)} :done, ${taskId(milestone.id)}, ${timing}`;
}

function buildMermaid(milestones) {
  return [
    "gantt",
    "    title EurekaVault Delivery History — Commit Evidence Only",
    "    dateFormat YYYY-MM-DD",
    "    axisFormat %b %d",
    "",
    "    section Delivered",
    ...milestones.map(mermaidTask),
  ].join("\n");
}

function generatedDocument(mermaid, milestones) {
  return `# Generated EurekaVault Delivery History\n\n> Generated by \`scripts/generate-roadmap-gantt.mjs\` from retrospective commit-backed groups in \`docs/roadmap/milestones.yaml\`. It intentionally contains no future forecast or product commitment.\n\nHistorical delivery groups represented: **${milestones.length}**.\n\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n`;
}

async function main() {
  const yamlSource = await readFile(milestonesPath, "utf8");
  const milestones = parseMilestonesYaml(yamlSource);
  if (!milestones.length) throw new Error("No retrospective delivery groups were parsed from docs/roadmap/milestones.yaml.");

  for (const milestone of milestones) {
    if (!milestone.name) throw new Error(`${milestone.id}: name is required.`);
    if (milestone.status !== "completed") throw new Error(`${milestone.id}: only completed historical groups are allowed in the roadmap Gantt.`);
    requireDate(milestone, "start_date");
    requireDate(milestone, "target_date");
  }

  const mermaid = buildMermaid(milestones);
  await writeFile(outputPath, generatedDocument(mermaid, milestones), "utf8");

  const readme = await readFile(readmePath, "utf8");
  const start = readme.indexOf(startMarker);
  const end = readme.indexOf(endMarker);
  if (start === -1 || end === -1 || end < start) throw new Error("README.md is missing ROADMAP-GANTT generation markers.");

  const replacement = `${startMarker}\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n${endMarker}`;
  const updated = `${readme.slice(0, start)}${replacement}${readme.slice(end + endMarker.length)}`;
  await writeFile(readmePath, updated, "utf8");
  console.log(`Generated historical Gantt from ${milestones.length} commit-backed delivery groups.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
