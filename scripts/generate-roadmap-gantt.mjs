import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const milestonesPath = path.join(root, "docs", "roadmap", "milestones.yaml");
const outputPath = path.join(root, "docs", "roadmap", "generated-gantt.md");
const readmePath = path.join(root, "README.md");
const startMarker = "<!-- ROADMAP-GANTT:START -->";
const endMarker = "<!-- ROADMAP-GANTT:END -->";

function unquote(value) {
  const trimmed = value.trim();
  if ((trimmed.startsWith("'") && trimmed.endsWith("'")) || (trimmed.startsWith('"') && trimmed.endsWith('"'))) {
    return trimmed.slice(1, -1).replace(/''/g, "'");
  }
  return trimmed;
}

function parseMilestonesYaml(source) {
  const milestones = [];
  let current = null;
  let nested = null;

  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, "");
    const idMatch = line.match(/^- id:\s*(.+)$/);
    if (idMatch) {
      current = { id: unquote(idMatch[1]) };
      milestones.push(current);
      nested = null;
      continue;
    }
    if (!current) continue;

    const topMatch = line.match(/^  ([a-zA-Z0-9_]+):\s*(.*)$/);
    if (topMatch) {
      const [, key, value] = topMatch;
      if (value === "") {
        nested = key;
        current[key] ??= {};
      } else {
        current[key] = unquote(value);
        nested = null;
      }
      continue;
    }

    const nestedMatch = line.match(/^    ([a-zA-Z0-9_]+):\s*(.+)$/);
    if (nestedMatch && nested) {
      const [, key, value] = nestedMatch;
      current[nested][key] = unquote(value);
    }
  }

  return milestones;
}

function taskId(value) {
  return value.replace(/[^a-zA-Z0-9]/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "").slice(0, 42) || "milestone";
}

function requireDate(milestone, field) {
  const value = milestone[field]?.value;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value || "")) {
    throw new Error(`${milestone.id}: ${field}.value must be YYYY-MM-DD.`);
  }
  return value;
}

function mermaidTask(milestone) {
  const start = requireDate(milestone, "start_date");
  const end = requireDate(milestone, "target_date");
  const id = taskId(milestone.id);
  const prefix = milestone.status === "completed" ? "done, " : milestone.status === "active" ? "active, " : "";
  const timing = start === end ? `${start}, 1d` : `${start}, ${end}`;
  return `    ${milestone.name.padEnd(43)} :${prefix}${id}, ${timing}`;
}

function buildMermaid(milestones) {
  const groups = [
    ["Completed", milestones.filter((m) => m.status === "completed")],
    ["Current - forecast", milestones.filter((m) => m.status === "active")],
    ["Planned - forecast", milestones.filter((m) => m.status === "planned")],
  ].filter(([, items]) => items.length);

  const lines = [
    "gantt",
    "    title EurekaVault Product Roadmap",
    "    dateFormat YYYY-MM-DD",
    "    axisFormat %b %d",
    "",
  ];

  for (const [section, items] of groups) {
    lines.push(`    section ${section}`);
    for (const milestone of items) lines.push(mermaidTask(milestone));
    lines.push("");
  }

  return lines.join("\n").trimEnd();
}

function generatedDocument(mermaid, milestones) {
  const completed = milestones.filter((m) => m.status === "completed").length;
  const active = milestones.filter((m) => m.status === "active").length;
  const planned = milestones.filter((m) => m.status === "planned").length;
  return `# Generated EurekaVault Roadmap Gantt\n\n> Generated by \`scripts/generate-roadmap-gantt.mjs\` from \`docs/roadmap/milestones.yaml\`. Do not edit the task list manually.\n\nMilestones represented: **${completed} completed**, **${active} active**, **${planned} planned**.\n\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n`;
}

async function main() {
  const yamlSource = await readFile(milestonesPath, "utf8");
  const milestones = parseMilestonesYaml(yamlSource);
  if (!milestones.length) throw new Error("No milestones were parsed from docs/roadmap/milestones.yaml.");

  const statuses = new Set(["completed", "active", "planned"]);
  for (const milestone of milestones) {
    if (!milestone.name) throw new Error(`${milestone.id}: name is required.`);
    if (!statuses.has(milestone.status)) throw new Error(`${milestone.id}: unsupported status '${milestone.status}'.`);
    requireDate(milestone, "start_date");
    requireDate(milestone, "target_date");
  }

  const mermaid = buildMermaid(milestones);
  await writeFile(outputPath, generatedDocument(mermaid, milestones), "utf8");

  const readme = await readFile(readmePath, "utf8");
  const start = readme.indexOf(startMarker);
  const end = readme.indexOf(endMarker);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README.md is missing the ROADMAP-GANTT generation markers.");
  }

  const replacement = `${startMarker}\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n${endMarker}`;
  const updated = `${readme.slice(0, start)}${replacement}${readme.slice(end + endMarker.length)}`;
  await writeFile(readmePath, updated, "utf8");

  console.log(`Generated ${path.relative(root, outputPath)} and refreshed the README Gantt from ${milestones.length} milestones.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
